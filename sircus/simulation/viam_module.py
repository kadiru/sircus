"""Local Sircus Viam module, adapted from the transferred WorldStateStore demo.

Only a standalone fake-only configuration generated by build_viam_config.py is
accepted. Robot 10 is the simulated drop arm; robot 14 remains a reserved role.
The ball/board physics comes from physics.py, not Viam's kinematic fake driver.
"""
import asyncio
import copy
import hashlib
import json
import math
import os
from pathlib import Path
import time
import uuid

import numpy as np
from scipy.spatial.transform import Rotation
from google.protobuf.field_mask_pb2 import FieldMask
from viam.components.arm import Arm
from viam.components.generic import Generic
from viam.components.gripper import Gripper
from viam.module.module import Module
from viam.proto.common import (GeometriesInFrame, Geometry, Pose, PoseInFrame,
                               RectangularPrism, Sphere, Transform, Vector3, WorldState)
from viam.proto.service.worldstatestore import StreamTransformChangesResponse
from viam.resource.easy_resource import EasyResource
from viam.services.motion import MotionClient
from viam.services.worldstatestore import WorldStateStore
from viam.utils import dict_to_struct

from physics import default_config, simulate, static_boxes, validate_config

ROOT = Path(__file__).resolve().parent
CONFIG_PATH = Path(os.environ.get("SIRCUS_VIAM_CONFIG", ROOT / "viam-config.local.json"))
SCENE_PATH = Path(os.environ.get("SIRCUS_SCENE_CONFIG", ROOT / "viam-scene.json"))
MODEL_HASH = "78e0fdc383cf6e1e5b0f9d44fdf1205e4c08a37eb5c0c2182c9f74291c51d3c0"
MODULE = None
VISUALS = None


def load_scene():
    config = json.loads(SCENE_PATH.read_text()) if SCENE_PATH.exists() else default_config()
    validate_config(config)
    return config


def check_simulation_config():
    """Fail closed on cloud, remotes, unknown components, changed model or driver."""
    config = json.loads(CONFIG_PATH.read_text())
    if config.get("cloud") or config.get("remotes"):
        raise RuntimeError("This adapter accepts a standalone local simulation only")
    if config.get("network", {}).get("bind_address") != "127.0.0.1:8080":
        raise RuntimeError("Expected the generated loopback-only Viam configuration")
    resources = {c["name"]: c for c in config.get("components", [])}
    if set(resources) != {"arm-10", "gripper-10", "sircus"}:
        raise RuntimeError("Unexpected components in simulation configuration")
    for name, api in (("arm-10", "arm"), ("gripper-10", "gripper")):
        item = resources[name]
        if item["model"] != "rdk:builtin:fake" or item["api"] != f"rdk:component:{api}":
            raise RuntimeError(f"Refusing non-fake resource {name}")
    attributes = resources["arm-10"]["attributes"]
    model = Path(attributes["model-path"]).resolve()
    if attributes.get("arm-model") or model != ROOT / "models/xarm850_kinematics.json":
        raise RuntimeError("Expected the pinned UFACTORY 850 model")
    if hashlib.sha256(model.read_bytes()).hexdigest() != MODEL_HASH:
        raise RuntimeError("The pinned UFACTORY 850 model has changed")
    if resources["sircus"]["model"] != "local:sircus:controller":
        raise RuntimeError("Unexpected controller model")
    return config


def pose(xyz=(0, 0, 0), rotation=None):
    """Matrix -> Viam orientation vector (ZYZ, with Viam's pole convention)."""
    matrix = np.eye(3) if rotation is None else np.asarray(rotation, dtype=float)
    normal = matrix[:, 2]
    lon = math.atan2(normal[1], normal[0])
    lat = math.acos(float(np.clip(normal[2], -1, 1)))
    base = Rotation.from_euler("ZY", [lon, lat]).as_matrix()
    twist = base.T @ matrix
    theta = math.atan2(twist[1, 0], twist[0, 0])
    if 1 - abs(normal[2]) <= 0.0001:
        theta += lon if normal[2] > 0 else -lon
    theta = (math.degrees(theta) + 180) % 360 - 180
    return Pose(x=xyz[0], y=xyz[1], z=xyz[2], o_x=normal[0], o_y=normal[1], o_z=normal[2], theta=theta)


def board_rotation(config):
    return Rotation.from_euler("xyz", config["board"]["rpy_deg"], degrees=True).as_matrix()


def pickup(config):
    table = config["table"]
    center, size = table["center_mm"], table["size_mm"]
    return list(config.get("pickup_mm", [350, -220,
            center[2] + size[2]/2 + config["ball"]["diameter_mm"]/2]))


def solids(config, frame=None):
    """Same configurable table, board and five bin boxes used for display/planning."""
    board = config["board"]
    rotation = board_rotation(config) if frame is None else frame["board_rotation"]
    center = board["center_mm"] if frame is None else frame["board_center_mm"]
    result = [("board-14-floating", center, board["size_mm"], rotation, (49, 202, 186))]
    for solid in static_boxes(config):
        color = (210, 215, 221) if solid["name"] == "table" else (236, 174, 57)
        result.append((solid["name"], solid["center_mm"], solid["size_mm"], None, color))
    return result


def geometry(name, xyz=(0, 0, 0), size=None, rotation=None, radius=None):
    center = pose(xyz, rotation)
    if radius is not None:
        return Geometry(label=name, center=center, sphere=Sphere(radius_mm=radius))
    return Geometry(label=name, center=center, box=RectangularPrism(dims_mm=Vector3(x=size[0], y=size[1], z=size[2])))


def transform(name, xyz, size=None, rotation=None, parent="world", radius=None, color=(230, 59, 111)):
    return Transform(reference_frame=name,
        uuid=uuid.uuid5(uuid.NAMESPACE_URL, "sircus-simulation/"+name).bytes,
        pose_in_observer_frame=PoseInFrame(reference_frame=parent, pose=pose(xyz, rotation)),
        physical_object=geometry(name, size=size, radius=radius),
        metadata=dict_to_struct({"color": {"r": color[0], "g": color[1], "b": color[2]}, "opacity": 1.0}))


class SircusScene(WorldStateStore, EasyResource):
    MODEL = "local:sircus:scene"

    @classmethod
    def validate_config(cls, config):
        return [], []

    @classmethod
    def new(cls, config, dependencies):
        global VISUALS
        self = cls(config.name)
        self.transforms = {}
        self.subscribers = set()
        self.config = load_scene()
        self.sync(self.config)
        self.ball(pickup(self.config))
        VISUALS = self
        return self

    async def list_uuids(self, **kwargs):
        return list(self.transforms)

    async def get_transform(self, uuid, **kwargs):
        return self.transforms[uuid]

    async def stream_transform_changes(self, **kwargs):
        queue = asyncio.Queue(maxsize=256)
        self.subscribers.add(queue)
        try:
            for value in list(self.transforms.values()):
                yield StreamTransformChangesResponse(change_type=1, transform=value)
            while True:
                yield await queue.get()
        finally:
            self.subscribers.discard(queue)

    async def do_command(self, command, **kwargs):
        if command.get("status"):
            return {"objects": [t.reference_frame for t in self.transforms.values()], "config": self.config}
        raise ValueError("Use the sircus controller for scene changes and runs")

    def update(self, value):
        kind = 3 if value.uuid in self.transforms else 1
        self.transforms[value.uuid] = value
        change = StreamTransformChangesResponse(change_type=kind, transform=value,
            updated_fields=FieldMask(paths=["pose_in_observer_frame", "physical_object", "metadata"]))
        for queue in self.subscribers:
            if queue.full():
                queue.get_nowait()
            queue.put_nowait(change)

    def sync(self, config, frame=None):
        self.config = copy.deepcopy(config)
        for name, xyz, size, rotation, color in solids(config, frame):
            self.update(transform(name, xyz, size, rotation, color=color))

    def ball(self, xyz, parent="world"):
        self.update(transform("oddball-75mm", xyz, parent=parent,
                              radius=self.config["ball"]["diameter_mm"]/2))


class SircusController(Generic, EasyResource):
    MODEL = "local:sircus:controller"

    @classmethod
    def validate_config(cls, config):
        return ["arm-10", "gripper-10", "sircus-scene", "rdk:service:motion/builtin"], []

    @classmethod
    def new(cls, config, dependencies):
        self = cls(config.name)
        self.config = load_scene()
        self.task = None
        self.state = {"status": "idle", "mode": "simulation", "physically_verified": False,
                      "drop_robot_id": 10, "board_robot_id": 14, "board_arm_mode": "floating_proxy"}
        self.events = []
        return self

    def record(self, event, **values):
        self.events.append({"event": event, "time": time.time(), **values})

    async def probe(self):
        check_simulation_config()
        robot = MODULE.parent
        await robot.refresh()
        arm = Arm.from_robot(robot, "arm-10")
        kinematics = await arm.get_kinematics(timeout=10)
        model = json.loads(kinematics[1])
        expected = json.loads((ROOT / "models/xarm850_kinematics.json").read_text())
        if model.get("links") != expected["links"] or model.get("joints") != expected["joints"]:
            raise RuntimeError("Connected arm does not report the pinned 850 model")
        return {"config_guard": "passed", "kinematics": "UFACTORY 850", "joints": len(model["joints"]),
                "pickup_xyz_mm": pickup(self.config), "config": self.config, **self.state}

    async def do_command(self, command, **kwargs):
        if command.get("status"):
            return {**self.state, "events": self.events}
        if command.get("probe"):
            return await self.probe()
        if command.get("stop"):
            if self.task and not self.task.done():
                self.task.cancel()
                try:
                    await self.task
                except asyncio.CancelledError:
                    pass
            return dict(self.state)
        if self.task and not self.task.done():
            raise RuntimeError("A trial is running; stop it before changing the scene")
        if "set_scene" in command:
            candidate = copy.deepcopy(command["set_scene"])
            validate_config(candidate)
            text = json.dumps(candidate, indent=2, allow_nan=False)
            temporary = SCENE_PATH.with_suffix(".tmp")
            temporary.write_text(text + "\n")
            temporary.replace(SCENE_PATH)
            self.config = candidate
            VISUALS.sync(candidate)
            VISUALS.ball(pickup(candidate))
            self.state.pop("result", None)
            self.state.pop("error", None)
            self.state.update(status="idle", step="scene_updated")
            self.events = []
            return {"updated": True, "config": candidate}
        if command.get("run"):
            check_simulation_config()
            action = command.get("action", {"u_mm": 0, "v_mm": 0, "gap_mm": 200})
            seed = command.get("seed", 0)
            if isinstance(seed, bool) or not isinstance(seed, (int, float)) or not math.isfinite(seed) or seed != int(seed):
                raise ValueError("seed must be an integer")
            seed = int(seed)
            delay = float(command.get("delay_s", 0.25))
            speed = float(command.get("playback_speed", 0.5))
            if not math.isfinite(delay) or not 0 <= delay <= 5 or not math.isfinite(speed) or not 0.1 <= speed <= 4:
                raise ValueError("delay_s must be 0..5; playback_speed must be 0.1..4")
            self.state.pop("result", None)
            self.state.pop("error", None)
            self.state.update(status="running", step="simulate")
            self.events = []
            self.task = asyncio.create_task(self.run_trial(copy.deepcopy(action), seed, delay, speed))
            return {"started": True, "mode": "simulation"}
        raise ValueError("Use status, probe, set_scene, run, or stop")

    async def run_trial(self, action, seed, delay, speed):
        result = None
        held = False
        try:
            await self.probe()
            config = copy.deepcopy(self.config)
            result = await asyncio.to_thread(simulate, config, action, seed=seed, frames=True)
            release = result["release_xyz_mm"]
            pick = pickup(config)
            radius = config["ball"]["diameter_mm"]/2
            hover = max(pick[2], release[2]) + radius + 100
            robot = MODULE.parent
            motion = MotionClient.from_robot(robot, "builtin")
            grip = Gripper.from_robot(robot, "gripper-10")
            down_rotation = Rotation.from_euler("y", 180, degrees=True).as_matrix()

            async def move(name, xyz):
                check_simulation_config()
                self.state["step"] = name
                obstacles = [geometry(n, p, s, r) for n, p, s, r, _ in solids(config)]
                attachments = []
                if held:
                    attachments = [transform("held-oddball", [0, 0, 0], parent="gripper-10", radius=radius)]
                target = pose(xyz, down_rotation)
                ok = await motion.move(component_name="gripper-10",
                    destination=PoseInFrame(reference_frame="world", pose=target),
                    world_state=WorldState(obstacles=[GeometriesInFrame(reference_frame="world", geometries=obstacles)],
                                           transforms=attachments),
                    extra={"timeout": 15.0}, timeout=45)
                if not ok:
                    raise RuntimeError(f"Viam rejected motion at {name}")
                actual = (await motion.get_pose("gripper-10", "world", timeout=10)).pose
                error = math.dist(xyz, [actual.x, actual.y, actual.z])
                yaw_error = abs((actual.theta-target.theta+180) % 360-180)
                if error > 2 or actual.o_z > -0.999 or yaw_error > 1:
                    raise RuntimeError(f"TCP readback mismatch at {name}: {error:.3f} mm")
                self.record(name, target_xyz_mm=xyz, position_error_mm=error, motion_ok=True)
                await asyncio.sleep(delay)

            VISUALS.sync(config)
            VISUALS.ball(pick)
            await move("approach", [pick[0], pick[1], hover])
            check_simulation_config()
            await grip.open()
            await move("descend", [pick[0], pick[1], pick[2]])
            check_simulation_config()
            raw = await grip.grab()
            self.record("modeled_grasp", raw_fake_grab=raw, physically_verified=False)
            held = True
            VISUALS.ball([0, 0, 0], "gripper-10")
            await move("lift", [pick[0], pick[1], hover])
            await move("transfer", [release[0], release[1], hover])
            await move("release", [release[0], release[1], release[2]])
            check_simulation_config()
            await grip.open()
            held = False
            VISUALS.ball(release)
            previous = 0
            for frame in result["frames"]:
                await asyncio.sleep(max(0, frame["t"]-previous)/speed)
                VISUALS.sync(config, frame)
                VISUALS.ball(frame["ball_xyz_mm"])
                previous = frame["t"]
            await move("retreat", [release[0], release[1], hover])
            await move("reset", [pick[0], pick[1], hover])
            self.state.update(status="complete", result={k: v for k, v in result.items() if k != "frames"})
        except asyncio.CancelledError:
            self.state.update(status="cancelled", error="Trial cancelled; no automatic reset")
            raise
        except Exception as error:
            self.state.update(status="aborted", error=f"{type(error).__name__}: {error}")
        finally:
            self.state["held_modeled"] = held
            log = {"state": self.state, "events": self.events, "action": action, "seed": seed,
                   "physics_result": result, "config": self.config}
            output = ROOT / "data" / "viam-runs"
            output.mkdir(parents=True, exist_ok=True)
            (output / f"{time.time_ns()}.json").write_text(json.dumps(log, indent=2, allow_nan=False))

    async def close(self):
        if self.task and not self.task.done():
            self.task.cancel()
            try:
                await self.task
            except asyncio.CancelledError:
                pass


async def main():
    global MODULE
    check_simulation_config()
    MODULE = Module.from_args()
    MODULE.add_model_from_registry(SircusScene.API, SircusScene.MODEL)
    MODULE.add_model_from_registry(SircusController.API, SircusController.MODEL)
    await MODULE.start()


if __name__ == "__main__":
    asyncio.run(main())
