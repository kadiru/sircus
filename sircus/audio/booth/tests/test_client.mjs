import assert from 'node:assert/strict';
import {SircusAudio} from '../integration/sircus-audio-client.mjs';
const calls=[],errors=[];
const audio=new SircusAudio({baseURL:'http://example.invalid',token:'TEST_ONLY',fetchImpl:async(url,options)=>{calls.push({url,options});await new Promise(r=>setTimeout(r,5));return {ok:true,json:async()=>({accepted:true})};},onError:e=>errors.push(e)});
assert.equal(audio.event('release',{trialId:'t',eventId:'r'}),undefined);
audio.event('capture',{trialId:'t',eventId:'c'});
while(audio.running)await new Promise(r=>setTimeout(r,5));
assert.deepEqual(calls.map(x=>JSON.parse(x.options.body).type),['release','capture']);
assert.equal(calls[0].options.headers.Authorization,'Bearer TEST_ONLY');
const failure=new SircusAudio({baseURL:'http://example.invalid',token:'TEST_ONLY',fetchImpl:async()=>{throw new Error('offline')},onError:e=>errors.push(e)});
assert.equal(failure.event('miss',{trialId:'t',eventId:'m'}),undefined);
while(failure.running)await new Promise(r=>setTimeout(r,5));
assert.equal(errors.length,1);console.log('Nonblocking client: immediate return, ordering, auth header, isolated failure passed');
const immutable=[];let release;
const gate=new Promise(resolve=>{release=resolve;});
const queued=new SircusAudio({baseURL:'http://example.invalid',token:'TEST_ONLY',maxQueue:2,fetchImpl:async(url,options)=>{await gate;immutable.push(JSON.parse(options.body));return {ok:true,json:async()=>({accepted:true})};}});
queued.emit({schema:'sircus.audio.v1',event_id:'first'});
const record={schema:'sircus.audio.v1',event_id:'second',source:'simulation'};queued.emit(record);record.source='sensor';release();
while(queued.running)await new Promise(r=>setTimeout(r,5));
assert.equal(immutable[1].source,'simulation');
const pending=[],cancelErrors=[];
const cancelled=new SircusAudio({baseURL:'http://example.invalid',token:'TEST_ONLY',onError:e=>cancelErrors.push(e),fetchImpl:(url,options)=>new Promise((resolve,reject)=>{pending.push({url,options,resolve});options.signal.addEventListener('abort',()=>reject(new Error('aborted')));})});
cancelled.event('release',{trialId:'stop-test'});cancelled.event('impact',{trialId:'stop-test'});
const stopped=cancelled.stop('stop-test');pending[1].resolve({ok:true,json:async()=>({accepted:true})});await stopped;
while(cancelled.running)await new Promise(r=>setTimeout(r,5));
assert.equal(pending.length,2);assert.ok(pending[1].url.endsWith('/stop'));assert.equal(cancelled.queue.length,0);
const rejected=[];
const unaccepted=new SircusAudio({baseURL:'http://example.invalid',token:'TEST_ONLY',onError:e=>rejected.push(e),fetchImpl:async()=>({ok:true,json:async()=>({accepted:false,reason:'fx_disabled'})})});
unaccepted.event('release');while(unaccepted.running)await new Promise(r=>setTimeout(r,5));assert.equal(rejected.length,1);
console.log('Canonical evidence snapshot, queue cancellation, scoped stop and rejected-cue reporting passed');
